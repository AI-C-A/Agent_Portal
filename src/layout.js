const ORDER = Object.keys(BLOCKS);

// 블록 밖: y는 한 줄, x는 도로 위쪽 줄 / 아래쪽 줄을 따로 두고 큰길 위에서 섞는다
const FY = [[52, 12], [64, 24], [320, 280], [400, 288], [416, 304], [480, 352], [496, 368], [511, 376], [816, 674], [832, 692], [944, 804], [984, 812]];
const FX_TOP = [[32, 4], [96, 20], [448, 372], [600, 484], [1096, 980], [1120, 984], [1250, 1114], [1390, 1114], [1472, 1196], [1696, 1432], [1758, 1596]];
const FX_BOT = [[32, 4], [96, 20], [784, 708], [832, 716], [912, 796], [928, 812], [992, 844], [1008, 852], [1744, 1588], [1758, 1596]];
function pl(T, v) { // 구간 선형, 양끝 밖은 기울기 1
  if (v <= T[0][0]) return T[0][1] + (v - T[0][0]);
  for (let i = 1; i < T.length; i++) if (v <= T[i][0]) { const a = T[i - 1], b = T[i]; return a[1] + (b[1] - a[1]) * (v - a[0]) / (b[0] - a[0]); }
  const e = T[T.length - 1]; return e[1] + (v - e[0]);
}
export function blockAt(x, y) {
  for (let i = 0; i < ORDER.length; i++) { const b = BLOCKS[ORDER[i]], r = b.r; if (x >= r[0] && x <= r[2] && y >= r[1] && y <= r[3]) return b; }
  return null;
}
export function RM(x, y) {
  const b = blockAt(x, y);
  if (b) return [x + b.d[0], y + b.d[1]];
  const k = Math.max(0, Math.min(1, (y - 416) / 64));
  return [pl(FX_TOP, x) * (1 - k) + pl(FX_BOT, x) * k, pl(FY, y)];
}
export const rx = (x, y) => RM(x, y)[0];
export const ry = (x, y) => RM(x, y)[1];
// 사각형: 한 블록 안이면 통째로 옮기고, 아니면 두 꼭짓점을 따로 바꾼다
export function RR(r) {
  const b = blockAt(r[0], r[1]);
  if (b && b === blockAt(r[2], r[3])) return [r[0] + b.d[0], r[1] + b.d[1], r[2] + b.d[0], r[3] + b.d[1]];
  const a = RM(r[0], r[1]), c = RM(r[2], r[3]); return [a[0], a[1], c[0], c[1]];
}
export const RP = (pts) => pts.map((p) => RM(p[0], p[1])); // [[x, y]...]
// 블록이 새 맵에서 차지하는 사각형
export function blockRect(id) { const b = BLOCKS[id], r = b.r; return [r[0] + b.d[0], r[1] + b.d[1], r[2] + b.d[0], r[3] + b.d[1]]; }
