// 건물 내부는 원래 좌표로 그린다. 건물마다(블록) 원래 영역 r = [x0, y0, x1, y1]과 옮길 거리 d = [dx, dy]를 두고,
// 굽기·대본·자율 행동 모듈은 원래 좌표를 RM(x, y)로 바꿔 쓴다. 블록 밖(도로·잔디·숲)은 축마다 구간 선형으로 줄인다.
//   RM(x, y) → [x, y]   원래 좌표 → 새 좌표       RR([x0, y0, x1, y1]) → 새 사각형
//   BLOCKS[id]          블록 (주차장은 차량 한 줄을 덜어 네 조각, 세차장·행정반은 정비고 옆으로 옮겼다)
// 울타리는 화면 끝에 있고, 그 바깥 숲(PAD)은 이미지에만 구워 두어 시연 클로즈업에서만 보인다.
// 오른쪽 숲(PAD_R)은 더 넓다 — 시연은 오른쪽 팝업 열(화면 x 1204~)을 비우고 맞추므로 그 뒤로 숲이 보이게.
