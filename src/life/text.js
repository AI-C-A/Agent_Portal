export function rankVal(r) {
  if (!r) return 0;
  const t = r[0], n = parseInt(r[1], 10) || 1;
  return t === 'e' ? n : t === 'n' ? 10 + n : t === 'o' ? 20 + n : t === 'f' ? 30 + n : 0;
}
